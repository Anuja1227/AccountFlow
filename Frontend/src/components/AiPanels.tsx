let healthCache: Promise<AiHealth> | null = null

/** AI provider status, fetched once per page load. */
// eslint-disable-next-line react-refresh/only-export-components
export function useAiHealth() {
    const { can } = useAuth()
    const allowed = can(P.aiUse)
    const [health, setHealth] = useState<AiHealth | null>(null)

    useEffect(() => {
        if (!allowed) return
        healthCache ??= get<AiHealth>('/ai/status')
        healthCache.then(setHealth).catch(() => {
            healthCache = null
            setHealth({ provider: '?', model: '?', configured: false, reachable: false, external: false, message: 'Could not check the AI provider.' })
        })
    }, [allowed])

    return { allowed, health, ready: !!health?.reachable }
}

export function AiBadge({ health }: { health: AiHealth | null }) {
    if (!health) return <span className="ai-badge muted">AI: checking…</span>
    return (
        <span className={`ai-badge ${health.reachable ? 'ok' : 'off'}`} title={health.message}>
            ✦ AI {health.reachable ? `· ${health.provider} ${health.model}` : 'unavailable'}
        </span>
    )
}

export function AiDisclaimer({ provider, model }: { provider: string; model: string }) {
    return (
        <p className="ai-disclaimer">
            Generated by {provider} ({model}). AI can be wrong — review before using. Client identifiers were redacted
            before sending. TAT, SLA and RFT figures come from the system, not the AI.
        </p>
    )
}

export function UnverifiedNumbers({ numbers }: { numbers: string[] }) {
    if (numbers.length === 0) return null
    return (
        <p className="ai-warning" role="note">
            ⚠ The AI mentioned figures not present in the system data ({numbers.slice(0, 6).join(', ')}). Rely on the
            system-calculated values shown on this page.
        </p>
    )
}

type MisInsights = {
    interactionId: number
    headline: string
    insights: string[]
    recommendations: string[]
    unverifiedNumbers: string[]
    provider: string
    model: string
}

export function MisInsightsPanel({ filters }: { filters: { cse: string; location: string; segment: string } }) {
    const { allowed, health, ready } = useAiHealth()
    const [result, setResult] = useState<MisInsights | null>(null)
    const [error, setError] = useState('')
    const [busy, setBusy] = useState(false)

    // Insights belong to a filter selection; clear them when filters change.
    const key = `${filters.cse}|${filters.location}|${filters.segment}`
    useEffect(() => {
        setResult(null)
        setError('')
    }, [key])

    if (!allowed) return null

    async function run() {
        setBusy(true)
        setError('')
        try {
            setResult(
                await post<MisInsights>('/ai/mis-insights', {
                    cse: filters.cse || null,
                    location: filters.location || null,
                    segment: filters.segment || null,
                }),
            )
        } catch (err) {
            setError(errorMessage(err))
        } finally {
            setBusy(false)
        }
    }

    return (
        <section className="panel ai-panel">
            <div className="panel-heading">
                <div>
                    <h2>✦ AI management commentary</h2>
                    <p>Bottlenecks, rework sources and outliers for the current filters, written from the figures above.</p>
                </div>
                <AiBadge health={health} />
            </div>
            {!result && (
                <button type="button" className="ai-button" onClick={() => void run()} disabled={busy || !ready}>
                    {busy ? 'Analysing…' : 'Generate commentary'}
                </button>
            )}
            {!ready && health && <p className="muted small">{health.message}</p>}
            {error && <div className="error-banner">{error}</div>}
            {result && (
                <div className="ai-result">
                    <h3>{result.headline}</h3>
                    <ul>
                        {result.insights.map((i) => (
                            <li key={i}>{i}</li>
                        ))}
                    </ul>
                    {result.recommendations.length > 0 && (
                        <>
                            <h4>Recommended actions</h4>
                            <ul>
                                {result.recommendations.map((r) => (
                                    <li key={r}>{r}</li>
                                ))}
                            </ul>
                        </>
                    )}
                    <UnverifiedNumbers numbers={result.unverifiedNumbers} />
                    <AiDisclaimer provider={result.provider} model={result.model} />
                    <button type="button" className="clear-button" onClick={() => void run()} disabled={busy}>
                        {busy ? 'Regenerating…' : 'Regenerate'}
                    </button>
                </div>
            )}
        </section>
    )
}

type CaseSummary = {
    interactionId: number
    summary: string
    nextStep: string
    pendingItems: string[]
    risks: string[]
    unverifiedNumbers: string[]
    provider: string
    model: string
}

export function CaseSummaryPanel({ referenceId, version }: { referenceId: string; version: number }) {
    const { allowed, health, ready } = useAiHealth()
    const [result, setResult] = useState<CaseSummary | null>(null)
    const [error, setError] = useState('')
    const [busy, setBusy] = useState(false)

    // A new workflow action makes the old briefing stale.
    useEffect(() => {
        setResult(null)
        setError('')
    }, [referenceId, version])

    if (!allowed) return null

    async function run() {
        setBusy(true)
        setError('')
        try {
            setResult(await post<CaseSummary>('/ai/case-summary', { referenceId }))
        } catch (err) {
            setError(errorMessage(err))
        } finally {
            setBusy(false)
        }
    }

    return (
        <section className="panel ai-panel">
            <div className="panel-heading">
                <div>
                    <h2>✦ AI case briefing</h2>
                    <p>What happened, what is pending and who acts next.</p>
                </div>
                <AiBadge health={health} />
            </div>
            {!result && (
                <button type="button" className="ai-button" onClick={() => void run()} disabled={busy || !ready}>
                    {busy ? 'Reading the case…' : 'Brief me on this case'}
                </button>
            )}
            {!ready && health && <p className="muted small">{health.message}</p>}
            {error && <div className="error-banner">{error}</div>}
            {result && (
                <div className="ai-result">
                    <p>{result.summary}</p>
                    <p>
                        <strong>Next step:</strong> {result.nextStep}
                    </p>
                    {result.pendingItems.length > 0 && (
                        <>
                            <h4>Pending</h4>
                            <ul>
                                {result.pendingItems.map((i) => (
                                    <li key={i}>{i}</li>
                                ))}
                            </ul>
                        </>
                    )}
                    {result.risks.length > 0 && (
                        <>
                            <h4>Risks</h4>
                            <ul>
                                {result.risks.map((i) => (
                                    <li key={i}>{i}</li>
                                ))}
                            </ul>
                        </>
                    )}
                    <UnverifiedNumbers numbers={result.unverifiedNumbers} />
                    <AiDisclaimer provider={result.provider} model={result.model} />
                    <button type="button" className="clear-button" onClick={() => void run()} disabled={busy}>
                        {busy ? 'Refreshing…' : 'Refresh briefing'}
                    </button>
                </div>
            )}
        </section>
    )
}

