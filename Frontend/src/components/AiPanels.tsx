// ------------------------------------------------------------------ Automation
// The AI automation results are shown where they apply (no separate panel):
//  - the newest pending suggestion in the case's next-action bar,
//  - reply reviews on their query thread, intake checks on the Overview,
//  - signed-form checks on the Documents tab, and every run in History.

export const KIND_LABEL: Record<string, string> = {
    IntakeCheck: 'Intake completeness check',
    ResponseReview: 'CSE reply review',
    DocumentCheck: 'Signed-form AI check',
}

export const OUTCOME_TONE: Record<string, string> = {
    Complete: 'success',
    Resolved: 'success',
    Incomplete: 'warning',
    NotResolved: 'warning',
    Uncertain: 'neutral',
    Failed: 'danger',
    IssuesFound: 'warning',
    NoIssuesFound: 'success',
}

export const OUTCOME_LABEL: Record<string, string> = {
    Complete: 'Complete',
    Resolved: 'Reply resolves query',
    Incomplete: 'Information missing',
    NotResolved: 'Reply incomplete',
    Uncertain: 'Needs a person',
    Failed: 'AI unavailable',
    IssuesFound: 'Issues found',
    NoIssuesFound: 'No issues found',
}

/** Confidence means nothing when the AI could not decide or did not run. */
export const showConfidence = (i: AiInsight) => i.outcome !== 'Failed' && i.outcome !== 'Uncertain' && i.confidence > 0

const findAction = (detail: CaseDetail, code: string, queryId: number | null) =>
    detail.availableActions.find((x) => x.code === code && (queryId == null || x.queryId === queryId))

/** How a pending suggestion can be acted on right now, or null when it no longer fits the case. */
// eslint-disable-next-line react-refresh/only-export-components
export function suggestionTarget(detail: CaseDetail, i: AiInsight): { kind: 'review'; action: AvailableAction; initial: Record<string, string> } | { kind: 'apply' } | null {
    const s = i.suggested
    if (i.actionStatus !== 'Pending' || !s) return null
    const target = findAction(detail, s.action, s.queryId)
    // "Start review" already done by hand is skipped when the suggestion is applied.
    const firstOk = findAction(detail, s.firstAction, s.firstQueryId) || (s.firstAction === 'start-review' && s.stepCount > 1 && !!target)
    if (!firstOk) return null
    // A drafted message is always opened for the person to read and edit before it is sent.
    if (s.details && target)
        return {
            kind: 'review',
            action: target,
            initial: { details: s.details, ...(s.discrepancyType ? { discrepancyType: s.discrepancyType } : {}) },
        }
    if (s.details && s.stepCount > 1) {
        // e.g. "start review → raise query": the first step has no text; the query form opens after it.
        return { kind: 'apply' }
    }
    return s.details ? null : { kind: 'apply' }
}

/** The newest pending AI suggestion that still fits the case. */
// eslint-disable-next-line react-refresh/only-export-components
export function currentSuggestion(detail: CaseDetail) {
    return detail.aiInsights.find((i) => suggestionTarget(detail, i) !== null) ?? null
}

/** The AI suggestion shown in the case's next-action bar. */
export function AiSuggestionCard({
    detail,
    insight,
    onReview,
    onChanged,
}: {
    detail: CaseDetail
    insight: AiInsight
    onReview: (action: AvailableAction, initial: Record<string, string>, insightId: number) => void
    onChanged: (message: string) => void
}) {
    const { inWorkspace, can } = useAuth()
    const [busy, setBusy] = useState('')
    const [error, setError] = useState('')
    const target = suggestionTarget(detail, insight)
    if (!target || !(inWorkspace(WS.operations) && can('workflow.operations'))) return null

    const label = insight.actionResult?.replace(/^Suggested:\s*/, '').replace(/\s*Operations decides\.?$/, '') ?? 'Next step'

    async function act(key: string, path: string, done: string) {
        setBusy(key)
        setError('')
        try {
            await post(path)
            onChanged(done)
        } catch (err) {
            setError(errorMessage(err))
        } finally {
            setBusy('')
        }
    }

    return (
        <div className="ai-suggestion">
            <div className="ai-suggestion-body">
                <div className={`ai-suggestion-title tone-${OUTCOME_TONE[insight.outcome] ?? 'neutral'}`}>
                    ✦ {CHECK_TITLE[insight.kind] ?? 'AI check'}: <span className="ai-line-result">{checkHeadline(insight)}</span>
                </div>
                <div className="ai-line-sub">
                    Suggested next step: <strong>{label}</strong>
                    {insight.queryId ? ` · query #${insight.queryId}` : ''} · {shortWhen(insight.createdAt)}
                </div>
                {error && <div className="error-banner">{error}</div>}
            </div>
            <div className="ai-suggestion-actions">
                {target.kind === 'review' ? (
                    <button type="button" className="primary-button ai-primary" disabled={!!busy} onClick={() => onReview(target.action, target.initial, insight.id)}>
                        Review &amp; {target.action.label.charAt(0).toLowerCase() + target.action.label.slice(1)}
                    </button>
                ) : (
                    <button
                        type="button"
                        className="primary-button ai-primary"
                        disabled={!!busy}
                        onClick={() => void act('apply', `/ai/insights/${insight.id}/apply`, `AI suggestion applied: ${label}.`)}
                    >
                        {busy === 'apply' ? 'Applying…' : `Apply: ${label}`}
                    </button>
                )}
                <button type="button" className="secondary-button" disabled={!!busy} onClick={() => void act('dismiss', `/ai/insights/${insight.id}/dismiss`, 'AI suggestion dismissed.')}>
                    Dismiss
                </button>
            </div>
        </div>
    )
}

const CHECK_TITLE: Record<string, string> = {
    IntakeCheck: 'AI check',
    ResponseReview: 'AI reply check',
    DocumentCheck: 'AI form check',
}

/** The result in a few words, e.g. "Segment missing" or "All details present". */
// eslint-disable-next-line react-refresh/only-export-components
export function checkHeadline(i: AiInsight): string {
    const items = i.findings.slice(0, 3).join(', ') + (i.findings.length > 3 ? ` +${i.findings.length - 3} more` : '')
    switch (i.outcome) {
        case 'Incomplete':
            return i.findings.length > 0 ? `${items} missing` : 'Information missing'
        case 'Complete':
            return 'All details present'
        case 'Resolved':
            return 'Reply answers the query'
        case 'NotResolved':
            return 'Reply does not answer everything'
        case 'IssuesFound':
            return `${i.findings.length || 'Some'} issue${i.findings.length === 1 ? '' : 's'} found`
        case 'NoIssuesFound':
            return 'No issues found'
        default:
            return OUTCOME_LABEL[i.outcome] ?? i.outcome
    }
}

/** The Stage 1 query raised from an intake check (the newest one raised on or after it). */
// eslint-disable-next-line react-refresh/only-export-components
export function intakeQuery(insight: AiInsight, queries: CaseQuery[]): CaseQuery | null {
    if (insight.kind !== 'IntakeCheck' || insight.outcome !== 'Incomplete') return null
    const from = insight.createdAt.slice(0, 10)
    const raised = queries.filter((q) => q.queryType === 'MissingInformation' && q.raisedAt.slice(0, 10) >= from)
    return raised.length === 0 ? null : raised.reduce((x, y) => (y.id > x.id ? y : x))
}

/** "14 Oct, 3:12 am" (or "14 Oct" for a date without a time). */
function shortWhen(value: string, withTime = true): string {
    // Server timestamps are UTC without a suffix; a plain date stays as it is.
    const d = new Date(withTime && !/[zZ]|[+-]\d\d:\d\d$/.test(value) ? `${value}Z` : value)
    if (Number.isNaN(d.getTime())) return value
    const day = d.toLocaleDateString('en-IN', { day: 'numeric', month: 'short' })
    return withTime ? `${day}, ${d.toLocaleTimeString('en-IN', { hour: 'numeric', minute: '2-digit' }).toLowerCase()}` : day
}

/** What happened after the check, in plain words. */
function nextStep(i: AiInsight): string | null {
    if (i.actionStatus === 'Pending') return 'Suggestion waiting for Operations to review'
    const r = i.actionResult ?? ''
    const plain = (label: string) =>
        /raise query to cse/i.test(label) ? 'Query sent to CSE' : /prepare form/i.test(label) ? 'Moved to form preparation' : label
    let m = r.match(/^Reviewed and sent by (.+?): (.+)$/)
    if (m) return `${plain(m[2])} by ${m[1]}`
    m = r.match(/^Applied: (.+)$/)
    if (m) return `${plain(m[1].split(' → ').pop() ?? m[1])}${i.appliedByName ? ` by ${i.appliedByName}` : ''}`
    m = r.match(/^AI did: (.+)$/)
    if (m) return `${plain(m[1].split(' → ').pop() ?? m[1])} by AI`
    return r || null
}

/**
 * One AI result (Overview, query threads), as option A: the result as the title, one line
 * on what happened next, and small "Check again" / "Details" links on the right.
 */
export function AiInsightNote({ insight, action, query }: { insight: AiInsight; action?: ReactNode; query?: CaseQuery | null }) {
    const [open, setOpen] = useState(false)
    const resolved = query?.status === 'Resolved'
    const tone = resolved ? 'success' : OUTCOME_TONE[insight.outcome] ?? 'neutral'
    const sub = resolved
        ? `Query #${query!.id} answered by CSE and accepted · ${shortWhen(query!.resolvedAt ?? insight.createdAt, false)}`
        : `${nextStep(insight) ? `${nextStep(insight)} · ` : ''}${shortWhen(insight.createdAt)}`

    // Details add what the card does not already say.
    const asked = query?.messages.find((m) => m.messageType === 'Query')
    const replied = query ? [...query.messages].reverse().find((m) => m.messageType === 'Response') : undefined
    const showFindings = !query && (insight.kind !== 'IntakeCheck' || insight.findings.length > 3)

    return (
        <div className={`ai-line ${tone}`}>
            <div className="ai-line-main">
                <div className="ai-line-title">
                    ✦ {CHECK_TITLE[insight.kind] ?? 'AI check'}: <span className="ai-line-result">{checkHeadline(insight)}{resolved ? ' → resolved' : ''}</span>
                </div>
                <div className="ai-line-sub">{sub}</div>
            </div>
            <div className="ai-line-links">
                {action}
                <button type="button" className="ai-line-link" aria-expanded={open} onClick={() => setOpen((v) => !v)}>
                    Details {open ? '▴' : '▾'}
                </button>
            </div>
            {open && (
                <div className="ai-line-details">
                    {query ? (
                        <>
                            {asked && (
                                <p>
                                    <span className="muted">Operations asked:</span> {asked.body}
                                </p>
                            )}
                            <p>
                                <span className="muted">CSE replied:</span> {replied ? replied.body : 'No reply yet.'}
                            </p>
                        </>
                    ) : (
                        <>
                            <p>{insight.summary}</p>
                            {showFindings && insight.findings.length > 0 && (
                                <ul>
                                    {insight.findings.map((f) => (
                                        <li key={f}>{f}</li>
                                    ))}
                                </ul>
                            )}
                        </>
                    )}
                    <p className="muted">AI ran {shortWhen(insight.createdAt)}</p>
                </div>
            )}
        </div>
    )
}
