// ------------------------------------------------------------------ Automation
// The AI automation results are shown where they apply (no separate panel):
//  - the newest pending suggestion in the case's next-action bar,
//  - reply reviews on their query thread, intake checks on the Overview,
//  - signed-form checks on the Documents tab, and every run in History.

export const KIND_LABEL: Record<string, string> = {
    IntakeCheck: 'Intake completeness check',
    ResponseReview: 'CSE reply review',
    DocumentCheck: 'Signed-form AI check',
}

export const OUTCOME_TONE: Record<string, string> = {
    Complete: 'success',
    Resolved: 'success',
    Incomplete: 'warning',
    NotResolved: 'warning',
    Uncertain: 'neutral',
    Failed: 'danger',
    IssuesFound: 'warning',
    NoIssuesFound: 'success',
}

export const OUTCOME_LABEL: Record<string, string> = {
    Complete: 'Complete',
    Resolved: 'Reply resolves query',
    Incomplete: 'Information missing',
    NotResolved: 'Reply incomplete',
    Uncertain: 'Needs a person',
    Failed: 'AI unavailable',
    IssuesFound: 'Issues found',
    NoIssuesFound: 'No issues found',
}

/** Confidence means nothing when the AI could not decide or did not run. */
export const showConfidence = (i: AiInsight) => i.outcome !== 'Failed' && i.outcome !== 'Uncertain' && i.confidence > 0

const findAction = (detail: CaseDetail, code: string, queryId: number | null) =>
    detail.availableActions.find((x) => x.code === code && (queryId == null || x.queryId === queryId))

/** How a pending suggestion can be acted on right now, or null when it no longer fits the case. */
// eslint-disable-next-line react-refresh/only-export-components
export function suggestionTarget(detail: CaseDetail, i: AiInsight): { kind: 'review'; action: AvailableAction; initial: Record<string, string> } | { kind: 'apply' } | null {
    const s = i.suggested
    if (i.actionStatus !== 'Pending' || !s) return null
    const target = findAction(detail, s.action, s.queryId)
    // "Start review" already done by hand is skipped when the suggestion is applied.
    const firstOk = findAction(detail, s.firstAction, s.firstQueryId) || (s.firstAction === 'start-review' && s.stepCount > 1 && !!target)
    if (!firstOk) return null
    // A drafted message is always opened for the person to read and edit before it is sent.
    if (s.details && target)
        return {
            kind: 'review',
            action: target,
            initial: { details: s.details, ...(s.discrepancyType ? { discrepancyType: s.discrepancyType } : {}) },
        }
    if (s.details && s.stepCount > 1) {
        // e.g. "start review → raise query": the first step has no text; the query form opens after it.
        return { kind: 'apply' }
    }
    return s.details ? null : { kind: 'apply' }
}

/** The newest pending AI suggestion that still fits the case. */
// eslint-disable-next-line react-refresh/only-export-components
export function currentSuggestion(detail: CaseDetail) {
    return detail.aiInsights.find((i) => suggestionTarget(detail, i) !== null) ?? null
}

/** The AI suggestion shown in the case's next-action bar. */
export function AiSuggestionCard({
    detail,
    insight,
    onReview,
    onChanged,
}: {
    detail: CaseDetail
    insight: AiInsight
    onReview: (action: AvailableAction, initial: Record<string, string>, insightId: number) => void
    onChanged: (message: string) => void
}) {
    const { inWorkspace, can } = useAuth()
    const [busy, setBusy] = useState('')
    const [error, setError] = useState('')
    const target = suggestionTarget(detail, insight)
    if (!target || !(inWorkspace(WS.operations) && can('workflow.operations'))) return null

    const label = insight.actionResult?.replace(/^Suggested:\s*/, '').replace(/\s*Operations decides\.?$/, '') ?? 'Next step'

    async function act(key: string, path: string, done: string) {
        setBusy(key)
        setError('')
        try {
            await post(path)
            onChanged(done)
        } catch (err) {
            setError(errorMessage(err))
        } finally {
            setBusy('')
        }
    }

    return (
        <div className="ai-suggestion">
            <div className="ai-suggestion-body">
                <div className="ai-suggestion-title">✦ AI suggests: {label}</div>
                <p>{insight.summary}</p>
                {insight.findings.length > 0 && (
                    <ul>
                        {insight.findings.slice(0, 4).map((f) => (
                            <li key={f}>{f}</li>
                        ))}
                    </ul>
                )}
                <div className="muted small">
                    {KIND_LABEL[insight.kind] ?? insight.kind}
                    {insight.queryId ? ` · query #${insight.queryId}` : ''}
                    {showConfidence(insight) ? ` · confidence ${Math.round(insight.confidence * 100)}%` : ''} · {dateTime(insight.createdAt)}
                </div>
                {error && <div className="error-banner">{error}</div>}
            </div>
            <div className="ai-suggestion-actions">
                {target.kind === 'review' ? (
                    <button type="button" className="primary-button ai-primary" disabled={!!busy} onClick={() => onReview(target.action, target.initial, insight.id)}>
                        Review &amp; {target.action.label.charAt(0).toLowerCase() + target.action.label.slice(1)}
                    </button>
                ) : (
                    <button
                        type="button"
                        className="primary-button ai-primary"
                        disabled={!!busy}
                        onClick={() => void act('apply', `/ai/insights/${insight.id}/apply`, `AI suggestion applied: ${label}.`)}
                    >
                        {busy === 'apply' ? 'Applying…' : `Apply: ${label}`}
                    </button>
                )}
                <button type="button" className="secondary-button" disabled={!!busy} onClick={() => void act('dismiss', `/ai/insights/${insight.id}/dismiss`, 'AI suggestion dismissed.')}>
                    Dismiss
                </button>
            </div>
        </div>
    )
}

/** Compact one-run summary (Overview, query threads). */
export function AiInsightNote({ insight }: { insight: AiInsight }) {
    return (
        <div className="ai-note-box">
            <div className="ai-note-head">
                <strong>✦ {KIND_LABEL[insight.kind] ?? insight.kind}</strong>
                <Pill tone={OUTCOME_TONE[insight.outcome] ?? 'neutral'}>{OUTCOME_LABEL[insight.outcome] ?? insight.outcome}</Pill>
                <span className="muted small">{dateTime(insight.createdAt)}</span>
            </div>
            <p className="small">{insight.summary}</p>
            {insight.findings.length > 0 && (
                <ul className="small">
                    {insight.findings.slice(0, 4).map((f) => (
                        <li key={f}>{f}</li>
                    ))}
                </ul>
            )}
            {insight.actionResult && insight.actionStatus !== 'Pending' && (
                <p className="muted small">
                    {insight.actionStatus === 'Applied' ? '✓ ' : ''}
                    {insight.actionResult}
                </p>
            )}
        </div>
    )
}
